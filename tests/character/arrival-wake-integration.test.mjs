import {test,before,after} from 'node:test';
import assert from 'node:assert/strict';
import {createLab,setupDuel,stepLab,THREE} from './support/headless-character.mjs';
let lab;
before(async()=>{lab=await createLab({useWardrobe:true});});
after(()=>lab?.dispose());

test('arrival is already lying down in first person before play, then opens the eyes before enabling get-up',()=>{
  setupDuel(lab,1.05,'third-person');lab.resetCombatState(true);lab.combatPointerHeld=false;lab.combatLatchSeconds=0;
  lab.setInteractionPartner(null);lab.player.teleport({x:-14,y:.865,z:-12});
  for(let i=0;i<60;i++)stepLab(lab);
  lab.player.controls.isLocked=false;
  const ground=lab.physics.getStandingPosition(new THREE.Vector3()).y-.865;
  assert.equal(lab.collapseOnArrival(),true);
  assert.equal(lab.viewMode,'first-person');
  assert.ok(lab.ragdoll.isSettled,'arrival unnecessarily simulates another falling body');
  const eye=lab.host.renderCamera.position.clone();
  assert.ok(eye.y-ground>.035&&eye.y-ground<.45,`arrival eye is ${eye.y-ground} m above the floor`);
  const bounds=new THREE.Box3().setFromObject(lab.activeCorpseRoot,true);
  assert.ok(bounds.max.y-ground<.65,`the body is still upright: ${bounds.max.y-ground} m`);
  assert.ok(Math.abs(bounds.min.y-ground)<.035,'the lying skin misses the floor');
  assert.equal(lab.arrivalEyes.hidden,false);
  assert.equal(lab.arrivalEyes.style.getPropertyValue('--eye-open'),'0');
  assert.equal(lab.recoveryPrompt.classList.contains('visible'),false);
  lab.update(1);assert.equal(lab.arrivalWakeElapsed,0,'pause advanced the eye opening');
  const press=()=>lab.onGlobalKeyDown(new KeyboardEvent('keydown',{code:lab.settings.controls.interact,bubbles:true}));
  press();assert.equal(lab.recoveryRequested,false,'an invisible prompt queued a get-up');
  lab.player.controls.isLocked=true;
  for(let i=0;i<100;i++)lab.update(1/60);
  const aperture=Number(lab.arrivalEyes.style.getPropertyValue('--eye-open'));
  assert.ok(aperture>0&&aperture<1,'eyes did not open progressively');
  assert.equal(lab.recoveryPrompt.classList.contains('visible'),false);
  press();assert.equal(lab.recoveryRequested,false);
  for(let i=0;i<130;i++)lab.update(1/60);
  assert.equal(lab.arrivalEyes.hidden,true);
  assert.equal(lab.recoveryPrompt.classList.contains('visible'),true);
  assert.ok(lab.host.renderCamera.position.distanceTo(eye)<.015,'the sleeping arrival pose drifted');
  press();assert.ok(lab.recovery,'get-up was not available after waking');
  for(let i=0;i<600&&lab.recovery;i++)lab.update(1/60);
  assert.equal(lab.recovery,null);assert.equal(lab.ragdoll,undefined);
  assert.ok(lab.host.renderCamera.position.y-ground>1.3,'get-up did not restore the standing eye');
});
